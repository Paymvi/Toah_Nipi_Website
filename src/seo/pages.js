export const storyPages = stories.map((story) => ({
  path: `/new/${story.slug}`,
  title: story.title,
  description: story.description,
  image: story.socialImage
    ? { ...story.socialImage, alt: story.imageAlt }
    : undefined,
  // Drafts stay reachable from /new but out of search results.
  noindex: Boolean(story.draft),
  lastmod: story.dateTime,
  story,
}));

export const notFoundPage = {
  title: "Page Not Found",
  description: "The page you were looking for could not be found.",
  noindex: true,
};

export const routes = [...pages, ...storyPages];

export function getRoute(path) {
  return routes.find((route) => route.path === path);
}

export function fullTitle(route) {
  if (route.fullTitle) return route.fullTitle;
  return route.title ? `${route.title} | ${TITLE_SUFFIX}` : SITE_NAME;
}

export function absoluteUrl(path) {
  return `${SITE_URL}${path}`;
}

export function previewImage(route) {
  return route.image || SOCIAL_IMAGES.default;
}
